// DecryptStreamToFile streams decryption from inputPath to outputPath using a passphrase.
func DecryptStreamToFile(inputPath, outputPath, passphrase string, token *CancelToken) error {
	identity, err := age.NewScryptIdentity(passphrase)
	if err != nil {
		return fmt.Errorf("failed to create scrypt identity: %w", err)
	}
	return decryptStream(inputPath, outputPath, identity, token)
}

// DecryptStreamToFileWithIdentity streams decryption using any native age identity.
func DecryptStreamToFileWithIdentity(inputPath, outputPath, identityText string, token *CancelToken) error {
	identity, err := parseIdentity(identityText)
	if err != nil {
		return err
	}
	return decryptStream(inputPath, outputPath, identity, token)
}

func decryptStream(inputPath, outputPath string, identity age.Identity, token *CancelToken) (err error) {
	inFile, err := os.Open(inputPath)
	if err != nil {
		return fmt.Errorf("failed to open input file: %w", err)
	}
	defer inFile.Close()

	// Peek first bytes to detect armor
	header := make([]byte, 35)
	n, _ := io.ReadFull(inFile, header)
	inFile.Seek(0, io.SeekStart)

	var r io.Reader = inFile
	if n >= 35 && bytes.HasPrefix(header[:n], []byte("-----BEGIN AGE ENCRYPTED FILE-----")) {
		ar := armor.NewReader(inFile)
		r = ar
	}

	out, err := age.Decrypt(r, identity)
	if err != nil {
		return fmt.Errorf("failed to decrypt: %w", err)
	}

	outFile, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("failed to create output file: %w", err)
	}
	defer cleanupIncompleteOutput(outFile, outputPath, &err)

	if _, err := io.Copy(outFile, cancelReader{reader: out, token: token}); err != nil {
		return fmt.Errorf("failed to write decrypted data: %w", err)
	}
	return nil
}

func cleanupIncompleteOutput(file *os.File, outputPath string, err *error) {
	closeErr := file.Close()
	if *err == nil && closeErr != nil {
		*err = fmt.Errorf("failed to close output file: %w", closeErr)
	}
	if *err != nil {
		_ = os.Remove(outputPath)
	}
}

// TarFiles creates a tar archive from the given file paths.
// fileNames[i] is the name to use in the archive for filePaths[i].
// Streams with minimal memory usage.
func TarFiles(filePaths []string, fileNames []string, outputPath string, token *CancelToken) (err error) {
	if len(filePaths) != len(fileNames) {
		return fmt.Errorf("file path and name counts differ")
	}
	outFile, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("failed to create output file: %w", err)
	}
	defer cleanupIncompleteOutput(outFile, outputPath, &err)

	tw := tar.NewWriter(outFile)
	defer tw.Close()

	for i, path := range filePaths {
		if token.IsCancelled() {
			return errCancelled
		}
		info, err := os.Stat(path)
		if err != nil {
			return fmt.Errorf("failed to stat %s: %w", path, err)
		}

		header, err := tar.FileInfoHeader(info, "")
		if err != nil {
			return fmt.Errorf("failed to create tar header: %w", err)
		}
		header.Name = fileNames[i]

		if err := tw.WriteHeader(header); err != nil {
			return fmt.Errorf("failed to write tar header: %w", err)
		}

		f, err := os.Open(path)
		if err != nil {
			return fmt.Errorf("failed to open %s: %w", path, err)
		}
		if _, err := io.Copy(tw, cancelReader{reader: f, token: token}); err != nil {
			f.Close()
			return fmt.Errorf("failed to write tar data: %w", err)
		}
		f.Close()
	}
	return nil
}

// TarGzipFiles creates a tar.gz archive from the given file paths.
// Streams with minimal memory usage (gzip internal buffer ~32KB).
func TarGzipFiles(filePaths []string, fileNames []string, outputPath string, token *CancelToken) (err error) {
	if len(filePaths) != len(fileNames) {
		return fmt.Errorf("file path and name counts differ")
	}
	outFile, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("failed to create output file: %w", err)
	}
	defer cleanupIncompleteOutput(outFile, outputPath, &err)

	gw := gzip.NewWriter(outFile)
	defer gw.Close()

	tw := tar.NewWriter(gw)
	defer tw.Close()

	for i, path := range filePaths {
		if token.IsCancelled() {
			return errCancelled
		}
		info, err := os.Stat(path)
		if err != nil {
			return fmt.Errorf("failed to stat %s: %w", path, err)
		}

		header, err := tar.FileInfoHeader(info, "")
		if err != nil {
			return fmt.Errorf("failed to create tar header: %w", err)
		}
		header.Name = fileNames[i]

		if err := tw.WriteHeader(header); err != nil {
			return fmt.Errorf("failed to write tar header: %w", err)
		}

		f, err := os.Open(path)
		if err != nil {
			return fmt.Errorf("failed to open %s: %w", path, err)
		}
		if _, err := io.Copy(tw, cancelReader{reader: f, token: token}); err != nil {
			f.Close()
			return fmt.Errorf("failed to write tar data: %w", err)
		}
		f.Close()
	}
	return nil
}

// TarSingleFile creates a tar archive containing a single file.
func TarSingleFile(filePath string, entryName string, outputPath string, token *CancelToken) (err error) {
	outFile, err := os.Create(outputPath)
	if err != nil {
		return fmt.Errorf("failed to create output file: %w", err)
	}
	defer cleanupIncompleteOutput(outFile, outputPath, &err)

	tw := tar.NewWriter(outFile)
	defer tw.Close()

	info, err := os.Stat(filePath)
	if err != nil {
		return fmt.Errorf("failed to stat %s: %w", filePath, err)
	}

	header, err := tar.FileInfoHeader(info, "")
	if err != nil {
		return fmt.Errorf("failed to create tar header: %w", err)
	}
	header.Name = entryName

	if err := tw.WriteHeader(header); err != nil {
		return fmt.Errorf("failed to write tar header: %w", err)
	}

	f, err := os.Open(filePath)
	if err != nil {
		return fmt.Errorf("failed to open %s: %w", filePath, err)
	}
	defer f.Close()

	if _, err := io.Copy(tw, cancelReader{reader: f, token: token}); err != nil {
		return fmt.Errorf("failed to write tar data: %w", err)
	}
	return nil
}

// TarFilesDelim creates a tar archive from newline-delimited file paths and names.
// gomobile cannot export []string, so we use "\n" as delimiter.
func TarFilesDelim(filePathsDelim string, fileNamesDelim string, outputPath string, token *CancelToken) error {
	paths := strings.Split(filePathsDelim, "\n")
	names := strings.Split(fileNamesDelim, "\n")
	return TarFiles(paths, names, outputPath, token)
}

// TarGzipFilesDelim creates a tar.gz archive from newline-delimited file paths and names.
// gomobile cannot export []string, so we use "\n" as delimiter.
func TarGzipFilesDelim(filePathsDelim string, fileNamesDelim string, outputPath string, token *CancelToken) error {
	paths := strings.Split(filePathsDelim, "\n")
	names := strings.Split(fileNamesDelim, "\n")
	return TarGzipFiles(paths, names, outputPath, token)
}
